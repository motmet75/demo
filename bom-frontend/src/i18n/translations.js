export const DEFAULT_LANGUAGE = 'en'

const languageByCode = Object.fromEntries(SUPPORTED_LANGUAGES.map((language) => [language.code, language]))

export function normalizeLanguage(value) {
  if (!value) return ''
  const code = String(value).trim().toLowerCase().replace(/_/g, '-')
  if (languageByCode[code]) return code
  if (code === 'zh' || code === 'zh-cn' || code === 'zh-hans' || code === 'cn-cn' || code.startsWith('zh-hans-')) return 'cn'
  if (code === 'zh-tw' || code === 'zh-hant' || code === 'tw-tw' || code === 'taiwan' || code === 'taiwanese' || code.startsWith('zh-hant-')) return 'tw'
  if (code === 'thai' || code === 'thailand') return 'th'
  const primary = code.split('-')[0]
  return languageByCode[primary] ? primary : ''
}

export function getLanguageMeta(language) {
  return languageByCode[normalizeLanguage(language)] || languageByCode[DEFAULT_LANGUAGE]
}

export function getCurrentLanguage() {
  if (typeof window === 'undefined') return DEFAULT_LANGUAGE
  try {
    const url = new URL(window.location.href)
    const queryLanguage = normalizeLanguage(url.searchParams.get('lang'))
    if (queryLanguage) return queryLanguage
  } catch {
    // ignore invalid URL state
  }
  try {
    const stored = normalizeLanguage(localStorage.getItem(LANGUAGE_STORAGE_KEY))
    if (stored) return stored
  } catch {
    // ignore blocked storage
  }
  const browserLanguage = normalizeLanguage(navigator.language || navigator.languages?.[0])
  return browserLanguage || DEFAULT_LANGUAGE
}

export function getCurrentLocale() {
  return getLanguageMeta(getCurrentLanguage()).locale
}

export function getBrowserTimeZone() {
  try {
    return Intl.DateTimeFormat().resolvedOptions().timeZone || ''
  } catch {
    return ''
  }
}

export function getCurrentTimeZone() {
  if (typeof window !== 'undefined') {
    try {
      const stored = String(localStorage.getItem(TIME_ZONE_STORAGE_KEY) || '').trim()
      if (stored) {
        Intl.DateTimeFormat('en-US', { timeZone: stored }).format()
        return stored
      }
    } catch {
      // Ignore invalid or blocked persisted values.
    }
  }
  return getBrowserTimeZone() || DEFAULT_TIME_ZONE
}

export function setCurrentTimeZone(value) {
  const timeZone = String(value || '').trim() || DEFAULT_TIME_ZONE
  Intl.DateTimeFormat('en-US', { timeZone }).format()
  if (typeof window !== 'undefined') {
    try { localStorage.setItem(TIME_ZONE_STORAGE_KEY, timeZone) } catch { /* storage may be blocked */ }
  }
  return timeZone
}
export function formatDateTimeValue(value, language = getCurrentLanguage(), options = {}) {
  if (!value) return ''
  const date = value instanceof Date ? value : new Date(value)
  if (Number.isNaN(date.getTime())) return ''
  return date.toLocaleString(getLanguageMeta(language).locale, {
    dateStyle: options.dateStyle || 'short',
    timeStyle: options.timeStyle || 'short',
    timeZone: options.timeZone || getCurrentTimeZone(),
  })
}

export function formatTimeValue(value, language = getCurrentLanguage(), options = {}) {
  const date = value instanceof Date ? value : new Date(value)
  if (Number.isNaN(date.getTime())) return ''
  return date.toLocaleTimeString(getLanguageMeta(language).locale, {
    hour: options.hour || '2-digit',
    minute: options.minute || '2-digit',
    timeZone: options.timeZone || getCurrentTimeZone(),
    ...(options.second ? { second: options.second } : {}),
  })
}

export function formatNumberValue(value, language = getCurrentLanguage(), options = {}) {
  const number = Number(value)
  if (!Number.isFinite(number)) return ''
  return number.toLocaleString(getLanguageMeta(language).locale, options)
}

export function formatMoneyValue(value, language = getCurrentLanguage(), currency = 'VND') {
  const number = Number(value)
  if (!Number.isFinite(number)) return ''
  try {
    return new Intl.NumberFormat(getLanguageMeta(language).locale, {
      style: 'currency',
      currency,
      maximumFractionDigits: currency === 'VND' ? 0 : 2,
    }).format(number)
  } catch {
    return `${formatNumberValue(number, language, { maximumFractionDigits: 0 })} ${currency}`
  }
}


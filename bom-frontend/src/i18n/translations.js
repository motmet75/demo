function interpolate(template, params = {}) {
  return String(template).replace(/\{(\w+)}/g, (_, key) => (
    params[key] == null ? '' : String(params[key])
  ))
}

export function tFor(language, key, params = {}) {
  const lang = normalizeLanguage(language) || DEFAULT_LANGUAGE
  const bundle = TRANSLATIONS[lang] || TRANSLATIONS[DEFAULT_LANGUAGE]
  const template = bundle[key] || TRANSLATIONS[DEFAULT_LANGUAGE][key] || key
  return interpolate(template, params)
}

export function sourceKeyFor(text) {
  const normalized = String(text || '').replace(/\s+/g, ' ').trim()
  return SOURCE_KEYS[normalized] || ''
}

export function translateSource(language, text) {
  const source = String(text ?? '')
  const trimmed = source.replace(/\s+/g, ' ').trim()
  if (!trimmed) return source

  const key = SOURCE_KEYS[trimmed]
  if (!key) return source

  const translated = tFor(language, key)
  if (translated === trimmed) return source

  const leading = source.match(/^\s*/)?.[0] || ''
  const trailing = source.match(/\s*$/)?.[0] || ''
  return `${leading}${translated}${trailing}`
}

export function translateRelativeTime(language, value, now = Date.now()) {
  const timestamp = Number(new Date(value || 0))
  if (!Number.isFinite(timestamp) || timestamp <= 0) return ''
  const minutes = Math.max(0, Math.floor((now - timestamp) / 60000))
  if (minutes < 1) return tFor(language, 'shop.justNow')
  if (minutes < 60) return tFor(language, 'shop.minutesAgo', { count: minutes })
  const hours = Math.floor(minutes / 60)
  if (hours < 24) return tFor(language, 'shop.hoursAgo', { count: hours })
  return tFor(language, 'shop.daysAgo', { count: Math.floor(hours / 24) })
}

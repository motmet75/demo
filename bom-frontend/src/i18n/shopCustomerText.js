export function shopCustomerText(language, key, vars = {}) {
  const code = normalizeLanguage(language) || 'en'
  const value = TEXT[code]?.[key] || TEXT.en[key] || key
  return value.replace(/\{(\w+)\}/g, (_, name) => vars[name] ?? '')
}

export function shopStatusText(language, status) {
  return shopCustomerText(language, `status.${status || 'PENDING'}`)
}
